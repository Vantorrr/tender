export function formatSourceLocation(source: {
  sourceFile?: string;
  page?: number | null;
  paragraph?: number | null;
  sheet?: string | null;
  cell?: string | null;
}): string {
  const parts = [source.sourceFile?.trim() || "файл не указан"];
  if (source.sheet) parts.push(`лист ${source.sheet}`);
  if (source.cell) parts.push(source.cell);
  else if (source.paragraph != null) parts.push(`абзац ${source.paragraph}`);
  else if (source.page) parts.push(`стр. ${source.page}`);
  return parts.join(", ");
}
